//! Derivation of keys from a passphrase.
//!
//! `master = Argon2id(passphrase, salt)`, then `HKDF-SHA256(master, label)` for each key, which is
//! required by the caller. The parameters and the salt are not secret, so they can be stored in
//! plain together with the encrypted data, to derive the same keys again later.

use crate::error::AinariError;
use crate::secret::Secret;
use argon2::{Algorithm, Argon2, Params, Version};
use hkdf::Hkdf;
use rand::RngExt;
use serde::{Deserialize, Serialize};
use sha2::Sha256;
use std::fmt;
use zeroize::Zeroize;

/// Length of all derived keys in bytes (256 bit).
pub const DERIVED_KEY_LEN: usize = 32;

/// Length of the salt, which is generated by `generate_kdf_salt`, and minimal length of a salt.
pub const KDF_SALT_LEN: usize = 16;

/// Lower and upper limits of the argon2-parameters. The lower limits prevent too weak keys, the
/// upper limits prevent, that parameters from an untrusted source exhaust the memory or the cpu,
/// because they are usually read together with the encrypted data, before it can be
/// authenticated.
pub const KDF_MIN_MEMORY_KIB: u32 = 19 * 1024;
pub const KDF_MAX_MEMORY_KIB: u32 = 2 * 1024 * 1024;
pub const KDF_MIN_ITERATIONS: u32 = 2;
pub const KDF_MAX_ITERATIONS: u32 = 16;
pub const KDF_MIN_PARALLELISM: u32 = 1;
pub const KDF_MAX_PARALLELISM: u32 = 16;

/// Parameters of Argon2id.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub struct KdfParams {
    /// Memory-cost in KiB
    pub memory_kib: u32,
    /// Number of passes over the memory
    pub iterations: u32,
    /// Number of lanes
    pub parallelism: u32,
}

/// Default is the second recommended option of RFC 9106 (64 MiB, 3 passes, 4 lanes).
impl Default for KdfParams {
    fn default() -> Self {
        KdfParams {
            memory_kib: 64 * 1024,
            iterations: 3,
            parallelism: 4,
        }
    }
}

impl KdfParams {
    /// Checks, that the parameters are within the allowed limits.
    ///
    /// # Returns
    ///
    /// Ok, if all parameters are valid, or `InvalidInput` with the name of the invalid parameter.
    pub fn validate(&self) -> Result<(), AinariError> {
        if !(KDF_MIN_MEMORY_KIB..=KDF_MAX_MEMORY_KIB).contains(&self.memory_kib) {
            return Err(AinariError::InvalidInput(format!(
                "kdf memory_kib must be between {KDF_MIN_MEMORY_KIB} and {KDF_MAX_MEMORY_KIB}"
            )));
        }
        if !(KDF_MIN_ITERATIONS..=KDF_MAX_ITERATIONS).contains(&self.iterations) {
            return Err(AinariError::InvalidInput(format!(
                "kdf iterations must be between {KDF_MIN_ITERATIONS} and {KDF_MAX_ITERATIONS}"
            )));
        }
        if !(KDF_MIN_PARALLELISM..=KDF_MAX_PARALLELISM).contains(&self.parallelism) {
            return Err(AinariError::InvalidInput(format!(
                "kdf parallelism must be between {KDF_MIN_PARALLELISM} and {KDF_MAX_PARALLELISM}"
            )));
        }
        Ok(())
    }
}

/// A derived key, which is wiped from memory, when it is dropped.
///
/// `Debug` prints `***`, so the key doesn't leak into logs as part of a bigger struct.
pub struct DerivedKey([u8; DERIVED_KEY_LEN]);

impl DerivedKey {
    /// Gives access to the raw key-bytes.
    pub fn as_bytes(&self) -> &[u8; DERIVED_KEY_LEN] {
        &self.0
    }
}

impl fmt::Debug for DerivedKey {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "***")
    }
}

impl Drop for DerivedKey {
    fn drop(&mut self) {
        self.0.zeroize();
    }
}

/// Generates a new random salt for `derive_master_key`.
pub fn generate_kdf_salt() -> [u8; KDF_SALT_LEN] {
    let mut salt = [0u8; KDF_SALT_LEN];
    rand::rng().fill(&mut salt);
    salt
}

/// Derives the master-key from a passphrase with Argon2id.
///
/// Argon2 is expensive by design, so this should run on a blocking thread-pool. The master-key
/// should not be used directly, but only as input for `expand_key`.
///
/// # Arguments
///
/// * `passphrase` - The passphrase
/// * `salt` - Salt, at least `KDF_SALT_LEN` bytes
/// * `params` - Argon2id-parameters
///
/// # Returns
///
/// The master-key, or `InvalidInput`, if the salt or the parameters are not valid.
pub fn derive_master_key(
    passphrase: &Secret,
    salt: &[u8],
    params: &KdfParams,
) -> Result<DerivedKey, AinariError> {
    if salt.len() < KDF_SALT_LEN {
        return Err(AinariError::InvalidInput(format!(
            "salt must have at least {KDF_SALT_LEN} bytes"
        )));
    }
    params.validate()?;

    argon2id(passphrase.reveal().as_bytes(), salt, params)
}

/// Derives a single key from the master-key with HKDF-SHA256.
///
/// The master-key already comes from a salted Argon2id, so HKDF doesn't need its own salt.
///
/// # Arguments
///
/// * `master` - The master-key from `derive_master_key`
/// * `label` - Purpose of the key. Different labels result in independent keys. It should contain
///   the context and a version, like `ainari-backup-v1 metadata-key`, so a key can't be re-used
///   for another purpose.
///
/// # Returns
///
/// The derived key.
pub fn expand_key(master: &DerivedKey, label: &[u8]) -> Result<DerivedKey, AinariError> {
    let mut key = DerivedKey([0u8; DERIVED_KEY_LEN]);
    Hkdf::<Sha256>::new(None, master.as_bytes())
        .expand(label, &mut key.0)
        .map_err(|e| AinariError::internal(format!("failed to expand key: {e}")))?;
    Ok(key)
}

/// Runs Argon2id without checking the limits of the parameters.
fn argon2id(passphrase: &[u8], salt: &[u8], params: &KdfParams) -> Result<DerivedKey, AinariError> {
    let argon2_params = Params::new(
        params.memory_kib,
        params.iterations,
        params.parallelism,
        Some(DERIVED_KEY_LEN),
    )
    .map_err(|e| AinariError::InvalidInput(format!("invalid kdf parameters: {e}")))?;

    let mut master = DerivedKey([0u8; DERIVED_KEY_LEN]);
    Argon2::new(Algorithm::Argon2id, Version::V0x13, argon2_params)
        .hash_password_into(passphrase, salt, &mut master.0)
        .map_err(|e| AinariError::internal(format!("failed to derive master-key: {e}")))?;
    Ok(master)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Smallest allowed parameters, so the tests stay fast.
    const MIN_PARAMS: KdfParams = KdfParams {
        memory_kib: KDF_MIN_MEMORY_KIB,
        iterations: KDF_MIN_ITERATIONS,
        parallelism: KDF_MIN_PARALLELISM,
    };

    const SALT: &[u8; KDF_SALT_LEN] = b"0123456789abcdef";

    /// Reference-vectors of Argon2id v1.3 from `src/test.c` of the reference-implementation
    /// (phc-winner-argon2) with password "password" and salt "somesalt".
    #[test]
    fn test_argon2id_reference_vectors() {
        let cases = [
            (
                2,
                256,
                1,
                "9dfeb910e80bad0311fee20f9c0e2b12c17987b4cac90c2ef54d5b3021c68bfe",
            ),
            (
                2,
                256,
                2,
                "6d093c501fd5999645e0ea3bf620d7b8be7fd2db59c20d9fff9539da2bf57037",
            ),
            (
                1,
                65536,
                1,
                "f6a5adc1ba723dddef9b5ac1d464e180fcd9dffc9d1cbf76cca2fed795d9ca98",
            ),
        ];
        for (iterations, memory_kib, parallelism, expected) in cases {
            let params = KdfParams {
                memory_kib,
                iterations,
                parallelism,
            };
            let master = argon2id(b"password", b"somesalt", &params).unwrap();
            assert_eq!(
                hex::encode(master.as_bytes()),
                expected,
                "params: {params:?}"
            );
        }
    }

    /// Reference-vectors of HKDF-SHA256, computed independently with the HKDF of the
    /// python-library `cryptography` and the master-key 0x00..0x1f.
    #[test]
    fn test_expand_key_reference_vectors() {
        let master = DerivedKey(std::array::from_fn(|i| i as u8));
        let cases: [(&[u8], &str); 3] = [
            (
                b"label-a",
                "b0d8f67a362945babe09ac0c6547a6bf9a3699bce326b704e42ac67d721453a9",
            ),
            (
                b"label-b",
                "88b9b18d6e907e1774533f000df453e13de77e0870242b4600be93d7e0c70a3b",
            ),
            (
                b"",
                "37ad29109f43265287804b674e2653d0a513718907f97fca97c95bded8104bbf",
            ),
        ];
        for (label, expected) in cases {
            let key = expand_key(&master, label).unwrap();
            assert_eq!(hex::encode(key.as_bytes()), expected);
        }
    }

    #[test]
    fn test_derive_master_key_deterministic() {
        let passphrase = Secret::from("passphrase");
        let first = derive_master_key(&passphrase, SALT, &MIN_PARAMS).unwrap();
        let second = derive_master_key(&passphrase, SALT, &MIN_PARAMS).unwrap();
        assert_eq!(first.as_bytes(), second.as_bytes());
    }

    #[test]
    fn test_derive_master_key_depends_on_inputs() {
        let passphrase = Secret::from("passphrase");
        let base = derive_master_key(&passphrase, SALT, &MIN_PARAMS).unwrap();

        let other_passphrase =
            derive_master_key(&Secret::from("passphrasf"), SALT, &MIN_PARAMS).unwrap();
        assert_ne!(base.as_bytes(), other_passphrase.as_bytes());

        let other_salt = derive_master_key(&passphrase, b"0123456789abcdeg", &MIN_PARAMS).unwrap();
        assert_ne!(base.as_bytes(), other_salt.as_bytes());

        let other_params = KdfParams {
            iterations: KDF_MIN_ITERATIONS + 1,
            ..MIN_PARAMS
        };
        let other_params = derive_master_key(&passphrase, SALT, &other_params).unwrap();
        assert_ne!(base.as_bytes(), other_params.as_bytes());
    }

    #[test]
    fn test_derive_master_key_invalid_input() {
        let passphrase = Secret::from("passphrase");

        let result = derive_master_key(&passphrase, b"short", &MIN_PARAMS);
        assert!(matches!(result, Err(AinariError::InvalidInput(_))));

        let invalid_params = [
            KdfParams {
                memory_kib: KDF_MIN_MEMORY_KIB - 1,
                ..MIN_PARAMS
            },
            KdfParams {
                memory_kib: KDF_MAX_MEMORY_KIB + 1,
                ..MIN_PARAMS
            },
            KdfParams {
                iterations: KDF_MIN_ITERATIONS - 1,
                ..MIN_PARAMS
            },
            KdfParams {
                iterations: KDF_MAX_ITERATIONS + 1,
                ..MIN_PARAMS
            },
            KdfParams {
                parallelism: 0,
                ..MIN_PARAMS
            },
            KdfParams {
                parallelism: KDF_MAX_PARALLELISM + 1,
                ..MIN_PARAMS
            },
        ];
        for params in invalid_params {
            let result = derive_master_key(&passphrase, SALT, &params);
            assert!(
                matches!(result, Err(AinariError::InvalidInput(_))),
                "params: {params:?}"
            );
        }
    }

    #[test]
    fn test_expand_key_independent_labels() {
        let master = derive_master_key(&Secret::from("passphrase"), SALT, &MIN_PARAMS).unwrap();
        let key_a = expand_key(&master, b"label-a").unwrap();
        let key_b = expand_key(&master, b"label-b").unwrap();
        assert_ne!(key_a.as_bytes(), key_b.as_bytes());
        assert_ne!(key_a.as_bytes(), master.as_bytes());
    }

    #[test]
    fn test_default_params_valid() {
        assert!(KdfParams::default().validate().is_ok());
    }

    #[test]
    fn test_generate_kdf_salt() {
        assert_ne!(generate_kdf_salt(), generate_kdf_salt());
    }

    #[test]
    fn test_derived_key_hidden_in_output() {
        let key = DerivedKey([7u8; DERIVED_KEY_LEN]);
        assert_eq!(format!("{key:?}"), "***");
    }
}
